#!/usr/bin/env python3
"""Real engine renders for the transient shaper; analytic expectations only, never audio substitutes.

Part A drives the existing fixture-locked runtime_harness binary. It proves the
module's compile/load status against the harness endpoint contract and, through
the TransientShaperSpike adapter declared in the SAME source file, neutral-path
purity, stereo independence and block invariance on the harness's own signal.

Part B generates a thin test-local driver (same Cmajor C++ API and patterns as
spikes/runtime/harness.cpp, which is left untouched) to exercise the full
TransientShaper with constructed signals and arbitrary parameter events: the
stock harness has no channel for either (its input generator and its single
float32 "gain" schedule are hardcoded, see harness.cpp:78,111-115).

Nothing here simulates DSP as a substitute for a render: every measurement
comes from a real libCmajPerformer render, and Python only builds expectations.
"""
