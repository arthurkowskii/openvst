def bounded():
    resource.setrlimit(resource.RLIMIT_AS, (2*1024**3, 2*1024**3))
    resource.setrlimit(resource.RLIMIT_CPU, (40, 40))

def command(args, timeout=120, pre=bounded):
    start = time.perf_counter()
    p = subprocess.run([str(a) for a in args], cwd=ROOT, capture_output=True, text=True,
                       timeout=timeout, preexec_fn=pre)
    report['commands'].append({'argv': [str(a) for a in args], 'returncode': p.returncode,
                               'wall_ms': (time.perf_counter()-start)*1000,
                               'stdout': p.stdout[:2000], 'stderr': p.stderr[:2000]})
    return p

def check(name, condition, **metrics):
    report['checks'][name] = {'pass': bool(condition), **metrics}
    if not condition:
        raise AssertionError(f'{name}: FAILED')

def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]

def load_audio(prefix):
    a = array.array('f')
    a.frombytes(prefix.with_suffix('.f32').read_bytes())
    if sys.byteorder != 'little': a.byteswap()
    return a

def maxdiff(a, b):
    return max((abs(x-y) for x, y in zip(a, b)), default=0.0)

def render_harness(manifest, block, name):
    prefix = OUT / 'renders' / name
    p = command([EXE, LIB, manifest, block, prefix, name])
    if p.returncode:
        raise RuntimeError(f'{name}: {p.stderr}')
    info = json.loads(prefix.with_suffix('.json').read_text())
    info['name'] = name
    info['raw_sha256'] = hashlib.sha256(prefix.with_suffix('.f32').read_bytes()).hexdigest()
    report['renders'].append(info)
    return load_audio(prefix), info

